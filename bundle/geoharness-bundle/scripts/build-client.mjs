import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(packageRoot, 'src', 'client.tsx')
const stylePath = resolve(packageRoot, 'src', 'styles.css')
const outputPath = resolve(packageRoot, 'client.js')
const packageName = '@geoharness/harness-plugin'

export async function renderClientBundle() {
  const [source, css] = await Promise.all([
    readFile(sourcePath, 'utf8'),
    readFile(stylePath, 'utf8'),
  ])
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.CommonJS,
      jsx: ts.JsxEmit.ReactJSX,
      esModuleInterop: true,
      sourceMap: false,
    },
    fileName: sourcePath,
    reportDiagnostics: true,
  })
  const diagnostics = transpiled.diagnostics ?? []
  if (diagnostics.length > 0) {
    const host = {
      getCanonicalFileName: fileName => fileName,
      getCurrentDirectory: () => packageRoot,
      getNewLine: () => '\n',
    }
    throw new Error(ts.formatDiagnostics(diagnostics, host))
  }

  return `/* Generated by scripts/build-client.mjs. Do not edit directly. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;
    const __GE0HARNESS_CSS__ = ${JSON.stringify(css)};
${transpiled.outputText.split('\n').map(line => line.length > 0 ? `    ${line}` : '').join('\n')}
    return module.exports;
  },
});
`
}

export async function buildClient() {
  const output = await renderClientBundle()
  await writeFile(outputPath, output, 'utf8')
  return outputPath
}

if (process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildClient()
}
